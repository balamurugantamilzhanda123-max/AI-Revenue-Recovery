def deduct_product_stock(product_id: str, quantity: int, db: Session) -> bool:
    """Deduct product stock in database upon successful order confirmation."""
    try:
        prod = db.scalar(select(Product).where(Product.id == product_id))
        if prod:
            prod.stock = max(0, prod.stock - quantity)
            if prod.stock == 0:
                prod.availability = "OUT_OF_STOCK"
            db.commit()
            return True
    except Exception:
        db.rollback()
    return False


def calculate_risk_level(amount: float, failure_type: str, retry_count: int) -> dict[str, Any]:
    """
    Transparent Risk Evaluation Algorithm:
    - Order Amount:
        < ₹1,000 -> LOW (e.g. LED bulbs, USB cables)
        ₹1,000 - ₹10,000 -> MEDIUM (e.g. Ceiling fans, Power strips, Kettles)
        ₹10,000 - ₹50,000 -> HIGH (e.g. Inverters, Entry Laptops, Monitors)
        >= ₹50,000 -> CRITICAL / HIGH PRIORITY (e.g. Business Laptops ₹65,999, Workstations ₹89k, Gaming ₹1.15L)
    - Multipliers for failure type and attempts.
    """
    if amount < 1000:
        base_score = 0.25
        risk_level = "LOW"
    elif amount < 10000:
        base_score = 0.55
        risk_level = "MEDIUM"
    elif amount < 50000:
        base_score = 0.85
        risk_level = "HIGH"
    else:
        base_score = 0.98
        risk_level = "CRITICAL"

    if failure_type.upper() in {"NETWORK_ERROR", "PAYMENT_TIMEOUT"}:
        recommendation = f"High priority recovery: {risk_level} value order (₹{amount:,.2f}) experienced transient technical failure. Automated secure retry link generated."
        recoverability = "HIGH"
    elif failure_type.upper() == "CHECKOUT_ABANDONMENT":
        recommendation = f"High purchase intent detected: Customer reached payment for ₹{amount:,.2f}. Sent reservation recovery message."
        recoverability = "MEDIUM"
    elif retry_count >= 1:
        recommendation = f"Repeated payment failure ({retry_count + 1} attempts). Immediate human associate intervention required."
        recoverability = "MANUAL_REQUIRED"
    else:
        recommendation = f"Assess payment channel for {risk_level} risk order value of ₹{amount:,.2f}."
        recoverability = "MODERATE"

    return {
        "risk_level": risk_level,
        "risk_score": base_score,
        "recommendation": recommendation,
        "recoverability": recoverability,
    }
