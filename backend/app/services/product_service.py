# Backward compatibility reference
ELECTRICAL_PRODUCTS = CATALOG_ITEMS


def seed_products_if_needed(db: Session) -> None:
    """Seeds products into database if the products table is empty."""
    try:
        count = db.scalar(select(Product).limit(1))
        if count is None:
            for item in CATALOG_ITEMS:
                prod = Product(
                    id=item["id"],
                    name=item["name"],
                    category=item["category"],
                    subcategory=item.get("subcategory"),
                    description=item["description"],
                    price=Decimal(str(item["price"])),
                    discount_price=Decimal(str(item.get("discountPrice", item["price"]))),
                    stock=item.get("stock", 100),
                    image_url=item["image_url"],
                    rating=float(item.get("rating", 4.5)),
                    reviews_count=item.get("reviews_count", 50),
                    badge=item.get("badge"),
                    specifications=item.get("specs", {}),
                    availability=item.get("availability", "IN_STOCK"),
                )
                db.add(prod)
            db.commit()
    except Exception as e:
        db.rollback()
        # Fallback to in-memory catalog
        pass


def list_products(
    category: str | None = None,
    search: str | None = None,
    db: Session | None = None,
) -> list[dict[str, Any]]:
    """
    Returns products filtered by category and/or search term.
    Queries database first, falling back to memory catalog.
    """
    results: list[dict[str, Any]] = []

    # If DB session provided or can be created, try fetching from DB
    should_close_db = False
    if db is None:
        try:
            db = SessionLocal()
            should_close_db = True
        except Exception:
            db = None

    if db is not None:
        try:
            seed_products_if_needed(db)
            query = select(Product)
            if category and category.strip().lower() != "all":
                cat = category.strip()
                query = query.where(Product.category.ilike(f"%{cat}%"))
            if search and search.strip():
                s = f"%{search.strip()}%"
                query = query.where(
                    or_(
                        Product.name.ilike(s),
                        Product.description.ilike(s),
                        Product.category.ilike(s),
                        Product.subcategory.ilike(s),
                    )
                )
            db_products = db.scalars(query).all()
            if db_products:
                for p in db_products:
                    results.append(
                        {
                            "id": p.id,
                            "productId": p.id,
                            "name": p.name,
                            "category": p.category,
                            "subcategory": p.subcategory or "",
                            "price": float(p.price),
                            "discountPrice": float(p.discount_price) if p.discount_price else float(p.price),
                            "currency": "INR",
                            "stock": p.stock,
                            "in_stock": p.stock > 0,
                            "availability": p.availability or "IN_STOCK",
                            "rating": float(p.rating),
                            "reviews_count": p.reviews_count,
                            "reviewCount": p.reviews_count,
                            "badge": p.badge,
                            "image_url": p.image_url,
                            "image": p.image_url,
                            "description": p.description,
                            "specs": p.specifications or {},
                            "createdAt": p.created_at.isoformat() if p.created_at else None,
                            "updatedAt": p.updated_at.isoformat() if p.updated_at else None,
                        }
                    )
                return results
        except Exception:
            pass
        finally:
            if should_close_db and db is not None:
                db.close()

    # Fallback to in-memory catalog
    results = CATALOG_ITEMS
    if category and category.strip().lower() != "all":
        cat_lower = category.strip().lower()
        results = [p for p in results if cat_lower in p["category"].lower() or cat_lower in (p.get("subcategory") or "").lower()]
    if search and search.strip():
        s = search.strip().lower()
        results = [
            p
            for p in results
            if s in p["name"].lower()
            or s in p["description"].lower()
            or s in p["category"].lower()
            or s in (p.get("subcategory") or "").lower()
        ]
    return results


